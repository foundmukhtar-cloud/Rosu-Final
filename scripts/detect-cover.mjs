import puppeteer from 'puppeteer-core';
import { writeFileSync } from 'node:fs';

const CHROME = 'C:/Program Files/Google/Chrome/Application/chrome.exe';
const BASE = 'http://127.0.0.1:5173';
const TOTAL = 238;

const frames = [];
for (let n = 156; n <= TOTAL; n += 2) frames.push(n);

const browser = await puppeteer.launch({
  executablePath: CHROME,
  headless: true,
  args: ['--no-sandbox', '--hide-scrollbars'],
});
const page = await browser.newPage();
await page.goto(`${BASE}/`, { waitUntil: 'domcontentloaded' });

const detected = await page.evaluate(async (nums) => {
  const W = 1280;
  const H = 720;
  const canvas = document.createElement('canvas');
  canvas.width = W;
  canvas.height = H;
  const ctx = canvas.getContext('2d', { willReadFrequently: true });

  const isPaper = (r, g, b) => r > 190 && g > 180 && r - b > -12 && r - b < 48 && r - g < 18;

  const runsOnRow = (data, y) => {
    const runs = [];
    let start = -1;
    let last = -1;
    for (let x = 0; x < W; x += 1) {
      const i = (y * W + x) * 4;
      if (isPaper(data[i], data[i + 1], data[i + 2])) {
        if (start < 0) start = x;
        last = x;
      } else if (start >= 0 && x - last > 6) {
        runs.push([start, last]);
        start = -1;
      }
    }
    if (start >= 0) runs.push([start, last]);
    return runs.filter(([a, b]) => b - a > 40).map(([a, b]) => [a / W, b / W]);
  };

  const results = [];
  for (const n of nums) {
    const img = new Image();
    img.src = `/assets/rosu/hero-uad/frames/ezgif-frame-${String(n).padStart(3, '0')}.png`;
    await img.decode();
    ctx.drawImage(img, 0, 0, W, H);
    const { data } = ctx.getImageData(0, 0, W, H);

    const rows = [0.32, 0.45, 0.58, 0.72].map((f) => runsOnRow(data, Math.round(f * H)));

    const score = new Map();
    for (const row of rows) {
      for (const [a, b] of row) {
        const key = `${Math.round(a * 40)}:${Math.round(b * 40)}`;
        score.set(key, (score.get(key) ?? 0) + 1);
      }
    }

    let best = null;
    let bestCount = 0;
    for (const [key, count] of score) {
      const [a, b] = key.split(':').map((v) => Number(v) / 40);
      if (count > bestCount && b - a > 0.05) {
        bestCount = count;
        best = [a, b];
      }
    }

    if (!best) {
      results.push({ n, rect: null });
      continue;
    }

    const cx = Math.round(((best[0] + best[1]) / 2) * W);
    let top = -1;
    let bottom = -1;
    for (let y = 0; y < H; y += 1) {
      const i = (y * W + cx) * 4;
      if (isPaper(data[i], data[i + 1], data[i + 2])) {
        if (top < 0) top = y;
        bottom = y;
      } else if (top >= 0 && y - bottom > 8) {
        break;
      }
    }

    results.push({
      n,
      rect: top >= 0 ? { x: best[0], y: top / H, w: best[1] - best[0], h: (bottom - top) / H } : null,
    });
  }
  return results;
}, frames);

const valid = detected.filter((d) => d.rect);
console.log(`detected ${valid.length}/${detected.length} frames`);

const smooth = valid.map((entry, i) => {
  const window = valid.slice(Math.max(0, i - 2), Math.min(valid.length, i + 3));
  const avg = (key) => window.reduce((sum, item) => sum + item.rect[key], 0) / window.length;
  return { n: entry.n, x: avg('x'), y: avg('y'), w: avg('w'), h: avg('h') };
});

const keyframes = smooth
  .filter((_, i) => i % 3 === 0 || i === smooth.length - 1)
  .map((item) => ({
    p: Number(((item.n - 1) / (TOTAL - 1)).toFixed(4)),
    x: Number(item.x.toFixed(4)),
    y: Number(item.y.toFixed(4)),
    w: Number(item.w.toFixed(4)),
    h: Number(item.h.toFixed(4)),
  }));

console.log(keyframes.map((k) => `${k.p}: ${k.x}/${k.y}/${k.w}/${k.h}`).join('\n'));

const ts = `// Generated by cover detection — do not edit by hand.
import type { CoverKeyframe } from './frames';

export const heroUadCover: CoverKeyframe[] = ${JSON.stringify(keyframes, null, 2)};

export function coverAt(progress: number): CoverKeyframe {
  if (heroUadCover.length === 0) return { p: progress, x: 0.45, y: 0.26, w: 0.2, h: 0.52 };
  const clamped = Math.min(1, Math.max(0, progress));
  let a = heroUadCover[0];
  let b = heroUadCover[heroUadCover.length - 1];
  if (clamped <= a.p) {
    b = a;
  } else if (clamped >= b.p) {
    a = b;
  } else {
    for (let i = 0; i < heroUadCover.length - 1; i += 1) {
      if (clamped >= heroUadCover[i].p && clamped <= heroUadCover[i + 1].p) {
        a = heroUadCover[i];
        b = heroUadCover[i + 1];
        break;
      }
    }
  }
  const span = b.p - a.p;
  const t = span > 0 ? (clamped - a.p) / span : 0;
  return {
    p: clamped,
    x: a.x + (b.x - a.x) * t,
    y: a.y + (b.y - a.y) * t,
    w: a.w + (b.w - a.w) * t,
    h: a.h + (b.h - a.h) * t,
  };
}
`;

writeFileSync('src/lib/booklet.ts', ts);
console.log(`wrote ${keyframes.length} keyframes`);

await browser.close();
